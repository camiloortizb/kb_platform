-- ==============================================================================
-- TRIGGERS PARA UPDATED_AT AUTOMÁTICO
-- ==============================================================================
CREATE OR REPLACE FUNCTION public.handle_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = timezone('utc'::text, now());
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS set_brands_updated_at ON public.brands;
CREATE TRIGGER set_brands_updated_at BEFORE UPDATE ON public.brands FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS set_products_updated_at ON public.products;
CREATE TRIGGER set_products_updated_at BEFORE UPDATE ON public.products FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS set_b2b_clients_updated_at ON public.b2b_clients;
CREATE TRIGGER set_b2b_clients_updated_at BEFORE UPDATE ON public.b2b_clients FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

DROP TRIGGER IF EXISTS set_b2b_orders_updated_at ON public.b2b_orders;
CREATE TRIGGER set_b2b_orders_updated_at BEFORE UPDATE ON public.b2b_orders FOR EACH ROW EXECUTE FUNCTION public.handle_updated_at();

