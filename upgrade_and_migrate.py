    batch_upload('product_dimensions', dimensions_payload, batch_size=200)

    # 3. Images
    client.delete(f'{SUPABASE_URL}/rest/v1/product_images?id=gt.0', headers=HEADERS)
    batch_upload('product_images', images_payload, batch_size=200)

    # 4. Labels
    client.delete(f'{SUPABASE_URL}/rest/v1/product_labels?id=gt.0', headers=HEADERS)
    batch_upload('product_labels', labels_payload, batch_size=200)

    # ==========================================================================
    # 5. QUALITY AUDIT REPORT
    # ==========================================================================
    total_prods = len(products_payload)
    with_ean = sum(1 for p in products_payload if p['ean'])
    with_format = sum(1 for p in products_payload if p['format'])
    with_desc_full = sum(1 for p in products_payload if p['description_full'])
    with_desc_short = sum(1 for p in products_payload if p['description_short'])
    with_image = len(images_payload)
    with_labels = len(labels_payload)

