def process_and_harmonize():
    print(f'[*] Reading Excel sheets from {EXCEL_PATH}...')
    xls = pd.ExcelFile(EXCEL_PATH)

    df_base = pd.read_excel(xls, 'Base Maestra Productos')
    df_desc = pd.read_excel(xls, 'Descripciones')
    df_med = pd.read_excel(xls, 'Medidas')
    df_img = pd.read_excel(xls, 'Imagenes')
    df_rot = pd.read_excel(xls, 'Rotulos')
    df_fuentes = pd.read_excel(xls, '_FUENTES')
    df_prio = pd.read_excel(xls, 'Prioridad Marcas')

    # Fix Descripciones SKU column
    desc_sku_col = df_desc.columns[0]
    df_desc = df_desc.rename(columns={desc_sku_col: 'SKU', 'DESCRIPCION BREVE': 'desc_breve'})
    df_desc['SKU_clean'] = df_desc['SKU'].apply(clean_sku)
    desc_map = {}
    for _, row in df_desc.iterrows():
        sku_k = row['SKU_clean']
        if sku_k:
            desc_map[sku_k] = str(row.get('desc_breve', '')).strip() if pd.notna(row.get('desc_breve')) else ''

    # Brand priority and type map
    brand_prio_map = {}
    brand_type_map = {}
    for _, row in df_prio.iterrows():
        b_name = str(row['Marca']).strip().upper()
        brand_prio_map[b_name] = str(row.get('Prioridad', 'Media')).strip()
        brand_type_map[b_name] = str(row.get('TIPO', 'B2B')).strip()

    # Dimensions map
    dim_map = {}
    df_med['SKU_clean'] = df_med['SKU'].apply(clean_sku)
    for _, row in df_med.iterrows():
        sku_k = row['SKU_clean']
        if sku_k:
            dim_map[sku_k] = {
                'height_cm': clean_dim(row.get('ALTO')),
                'width_cm': clean_dim(row.get('ANCHO')),
                'depth_cm': clean_dim(row.get('PROFUNDIDAD')),
                'weight_raw': str(row.get('Formato', '')).strip() if pd.notna(row.get('Formato')) else None
            }

    # Labels map
    labels_map = {}
    df_rot['SKU_clean'] = df_rot['SKU'].apply(clean_sku)
    for _, row in df_rot.iterrows():
        sku_k = row['SKU_clean']
        url = normalize_url(row.get('Link'))
        if sku_k and url:
            labels_map[sku_k] = url

    # Images map
    images_extra_map = {}
    df_img['SKU_clean'] = df_img['SKU'].apply(clean_sku)
    for _, row in df_img.iterrows():
        sku_k = row['SKU_clean']
        link = normalize_url(row.get('LINK'))
        if sku_k and link:
            images_extra_map[sku_k] = link

    # Process Brands
    print('[*] Harmonizing Brands and Brand Sources...')
    all_brand_names = sorted(list(set(df_base['MARCA'].dropna().astype(str).str.strip().str.upper())))
    brands_to_upsert = []
    for b in all_brand_names:
        brands_to_upsert.append({
            'name': b,
            'type': brand_type_map.get(b, 'B2B'),
            'priority': brand_prio_map.get(b, 'Media')
        })

    # Upload / Upsert Brands
    res_b = client.post(f'{SUPABASE_URL}/rest/v1/brands', headers=HEADERS, json=brands_to_upsert)
    # Fetch all brands to map name -> brand_id
    res_b_all = client.get(f'{SUPABASE_URL}/rest/v1/brands?select=id,name', headers=HEADERS)
    brand_id_map = {item['name'].strip().upper(): item['id'] for item in res_b_all.json()}
    print(f'[✓] Synced {len(brand_id_map)} brands in Supabase.')

    # Process Brand Sources (_FUENTES)
    brand_sources_to_upsert = []
    for _, row in df_fuentes.iterrows():
        b_raw = str(row['Marca']).strip().upper()
        url = normalize_url(row.get('URL'))
        stype = str(row.get('Tipo', 'Oficial')).strip()
        if url:
            b_id = brand_id_map.get(b_raw)
            brand_sources_to_upsert.append({
                'brand_id': b_id,
                'brand_name': b_raw,
                'url': url,
                'source_type': stype,
                'crawl_status': 'pending'
            })

    # Clean old brand_sources and insert
    client.delete(f'{SUPABASE_URL}/rest/v1/brand_sources?id=gt.0', headers=HEADERS)
    res_bs = client.post(f'{SUPABASE_URL}/rest/v1/brand_sources', headers=HEADERS, json=brand_sources_to_upsert)
    print(f'[✓] Synced {len(brand_sources_to_upsert)} brand sources from _FUENTES.')

    # Process Master Products
    print('[*] Harmonizing 1299 Master Products by EAN and SKU...')
    products_payload = []
    dimensions_payload = []
    images_payload = []
    labels_payload = []

    for idx, row in df_base.iterrows():
        sku = clean_sku(row['SKU'])
        ean = clean_ean(row.get('EAN'))
        brand_str = str(row['MARCA']).strip().upper()
        brand_id = brand_id_map.get(brand_str)
        product_name = str(row['Producto']).strip()
        
        # Priority
        prio = str(row.get('Prioridad', 'BAJA')).strip().upper()
        if prio not in ('URGENTE', 'ALTA', 'MEDIA', 'BAJA'):
            prio = 'BAJA'

        # Format / Size
        raw_format = str(row.get('Formato', '')).strip() if pd.notna(row.get('Formato')) else ''
        if not raw_format or raw_format.lower() in ('nan', 'none', ''):
            format_extracted = extract_format_from_name(product_name)
        else:
            format_extracted = raw_format

        # Descriptions
        desc_full = str(row.get('DESCRIPCION COMPLETA', '')).strip() if pd.notna(row.get('DESCRIPCION COMPLETA')) else ''
        desc_short = desc_map.get(sku, '')
        if not desc_short and desc_full:
            desc_short = desc_full.split('.')[0] + '.' if '.' in desc_full else desc_full[:150]

        product_record = {
            'sku': sku,
            'ean': ean,
            'name': product_name,
            'brand_id': brand_id,
            'priority': prio,
            'format': format_extracted,
            'description_short': desc_short,
            'description_full': desc_full,
            'url_origen': None,
            'ruta_tecnica': 'RUTA_TEXTO',
            'raw_html_tecnico': desc_full,
            'verification_status': 'VERIFICADO_MATRIZ'
        }
        products_payload.append(product_record)

        # Dimensions
        dim_data = dim_map.get(sku, {})
        dimensions_payload.append({
            'sku': sku,
            'ean': ean,
            'height_cm': dim_data.get('height_cm'),
            'width_cm': dim_data.get('width_cm'),
            'depth_cm': dim_data.get('depth_cm'),
            'weight_raw': dim_data.get('weight_raw') or format_extracted
        })

        # Product Images
        primary_foto = normalize_url(row.get('FOTO'))
        img_order = 1
        if primary_foto:
            images_payload.append({
                'sku': sku,
                'ean': ean,
                'image_url': primary_foto,
                'display_order': img_order,
                'is_primary': True
            })
            img_order += 1
        
        extra_img = images_extra_map.get(sku)
        if extra_img and extra_img != primary_foto:
            images_payload.append({
                'sku': sku,
                'ean': ean,
                'image_url': extra_img,
                'display_order': img_order,
                'is_primary': (img_order == 1)
            })

        # Labels / Rótulos
        label_url = labels_map.get(sku)
        if label_url:
            labels_payload.append({
                'sku': sku,
                'ean': ean,
                'label_url': label_url
            })

    # Also merge all high-res gallery images from product_images.csv
    sku_to_ean_map = {p['sku']: p['ean'] for p in products_payload}
    if os.path.exists('supabase_migration/csv/product_images.csv'):
        df_csv_imgs = pd.read_csv('supabase_migration/csv/product_images.csv')
        df_csv_imgs['sku'] = df_csv_imgs['sku'].apply(clean_sku)
        for _, img_row in df_csv_imgs.iterrows():
            sku_k = img_row['sku']
            img_url = normalize_url(img_row.get('image_url'))
            if sku_k and img_url:
                images_payload.append({
                    'sku': sku_k,
                    'ean': sku_to_ean_map.get(sku_k),
                    'image_url': img_url,
                    'display_order': int(img_row.get('display_order', 1)),
                    'is_primary': bool(img_row.get('is_primary', False))
                })

    # Deduplicate images per (sku, image_url)
    seen_imgs = set()
    dedup_images = []
    for img in images_payload:
        key = (img['sku'], img['image_url'])
        if key not in seen_imgs:
            seen_imgs.add(key)
            dedup_images.append(img)
    images_payload = dedup_images

    # ==========================================================================
    # 4. BATCH UPLOAD TO SUPABASE
    # ==========================================================================
    def batch_upload(table_name: str, records: List[Dict[str, Any]], batch_size: int = 200, on_conflict: Optional[str] = None):
        total = len(records)
        print(f'[*] Uploading {total} rows to {table_name} (batch_size={batch_size})...')
        url = f'{SUPABASE_URL}/rest/v1/{table_name}'
        if on_conflict:
            url += f'?on_conflict={on_conflict}'
        
        for i in range(0, total, batch_size):
            batch = records[i:i + batch_size]
            res = client.post(url, headers=HEADERS, json=batch)
            if res.status_code not in (200, 201):
                print(f'[!] Error in {table_name} batch {i}-{i+len(batch)}: {res.status_code} {res.text}')
                return False
        print(f'[✓] Uploaded {total} rows to {table_name}.')
        return True

    # 1. Products (on_conflict=sku)
    batch_upload('products', products_payload, batch_size=200, on_conflict='sku')

    # Fetch product IDs by SKU to link child tables
    print('[*] Fetching product_id references for relational linkage...')
    res_p_all = client.get(f'{SUPABASE_URL}/rest/v1/products?select=id,sku,ean', headers=HEADERS)
    sku_to_pid = {item['sku']: item['id'] for item in res_p_all.json()}

