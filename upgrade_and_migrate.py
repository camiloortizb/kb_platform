# 2. DATA NORMALIZATION HELPERS
# ==============================================================================
FORMAT_REGEX = re.compile(
    r'\b(\d+(?:[\.,]\d+)?\s*(?:ml|g|kg|l|oz|fl\.?\s*oz|sheets?|pads?|pcs?|ea|unidades?|par(?:es)?|capsules?|tablets?|stick))\b',
    re.IGNORECASE
)

def clean_ean(val) -> Optional[str]:
    if pd.isna(val) or val is None:
        return None
    val_str = str(val).strip()
    if val_str.endswith('.0'):
        val_str = val_str[:-2]
    try:
        if 'e' in val_str.lower():
            val_str = f"{int(float(val_str))}"
    except Exception:
        pass
    val_clean = ''.join(c for c in val_str if c.isdigit())
    return val_clean if len(val_clean) >= 8 else None

def clean_sku(val) -> str:
    if pd.isna(val) or val is None:
        return ''
    val_str = str(val).strip()
    if val_str.endswith('.0'):
        val_str = val_str[:-2]
    return val_str

def extract_format_from_name(name: str) -> Optional[str]:
    if not name:
        return None
    match = FORMAT_REGEX.search(name)
    if match:
        return match.group(1).strip()
    return None

def clean_dim(val) -> Optional[float]:
    if pd.isna(val) or val is None:
        return None
    if isinstance(val, (datetime.datetime, datetime.date)):
        return round(float(val.day) + float(val.month) / 10.0, 2)
    val_str = str(val).replace(',', '.').strip().lower()
    val_str = val_str.replace('cm', '').replace('mm', '').strip()
    try:
        return round(float(val_str), 2)
    except Exception:
        return None

def normalize_url(url_val) -> Optional[str]:
    if pd.isna(url_val) or url_val is None:
        return None
    url_str = str(url_val).strip()
    if url_str.startswith(('http://', 'https://')):
        return url_str
    elif url_str.startswith('//'):
        return 'https:' + url_str
    return None

